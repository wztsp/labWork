-- ============================================================
-- 03-antibiotics.sql   原 AntibioticDataInitializer
-- 建 lis_antibiotic / lis_antibiotic_breakpoint 表 + 内置 57 种抗生素 + CLSI M100 折点。
-- 幂等。注意: 折点为标量表达式(≤2/≥4), 供 CLSI 判读引擎(BreakpointExpr)解析。
-- ============================================================
CREATE TABLE IF NOT EXISTS lis_antibiotic (
    id BIGSERIAL PRIMARY KEY,
    antibiotic_code VARCHAR(32) NOT NULL,
    antibiotic_name VARCHAR(100) NOT NULL,
    category VARCHAR(50),
    unit VARCHAR(20),
    status SMALLINT DEFAULT 1,
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_lis_antibiotic ON lis_antibiotic (antibiotic_code);

CREATE TABLE IF NOT EXISTS lis_antibiotic_breakpoint (
    id BIGSERIAL PRIMARY KEY,
    antibiotic_id BIGINT,
    bacteria_id BIGINT,
    method VARCHAR(20),
    standard VARCHAR(20),
    standard_version VARCHAR(30),
    s_breakpoint VARCHAR(30),
    r_breakpoint VARCHAR(30),
    i_breakpoint VARCHAR(30),
    s_dd VARCHAR(30),
    r_dd VARCHAR(30),
    status SMALLINT DEFAULT 1,
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_bp_pair ON lis_antibiotic_breakpoint (antibiotic_id, bacteria_id, method);
CREATE INDEX IF NOT EXISTS idx_bp_antibiotic ON lis_antibiotic_breakpoint (antibiotic_id);
CREATE INDEX IF NOT EXISTS idx_bp_bacteria ON lis_antibiotic_breakpoint (bacteria_id);
CREATE INDEX IF NOT EXISTS idx_bp_standard ON lis_antibiotic_breakpoint (standard, standard_version);

