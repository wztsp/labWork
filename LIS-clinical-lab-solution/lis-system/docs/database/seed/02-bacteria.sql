CREATE TABLE IF NOT EXISTS lis_bacteria (
    id BIGSERIAL PRIMARY KEY,
    bacteria_code VARCHAR(32) NOT NULL,
    bacteria_name VARCHAR(100) NOT NULL,
    bacteria_name_latin VARCHAR(150),
    gram_type VARCHAR(10),
    bacteria_category VARCHAR(50),
    morphology VARCHAR(30),
    is_common SMALLINT DEFAULT 0,
    status SMALLINT DEFAULT 1,
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_lis_bacteria_code ON lis_bacteria (bacteria_code);
CREATE INDEX IF NOT EXISTS idx_lis_bacteria_gram ON lis_bacteria (gram_type);
CREATE INDEX IF NOT EXISTS idx_lis_bacteria_category ON lis_bacteria (bacteria_category);

